// Generates the Mermaid entity-relationship diagram in docs/technical/DATA-MODEL.md
// from apps/api/prisma/schema.prisma, between the marker comments below.
//
//   node deploy/schema-diagram.mjs           check only; exits 1 when the diagram is stale
//   node deploy/schema-diagram.mjs --write   rewrite the diagram in place
//
// The diagram shows every table with its key columns (PK, FK, UK) and every
// relation; the column lists and constraints are described in the document's text.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** Marker comment that opens the generated block. */
export const START = '<!-- schema-diagram:start (generated by deploy/schema-diagram.mjs) -->';
/** Marker comment that closes the generated block. */
export const END = '<!-- schema-diagram:end -->';

const root = new URL('../', import.meta.url);
const schemaPath = new URL('apps/api/prisma/schema.prisma', root);
const documentPath = new URL('docs/technical/DATA-MODEL.md', root);

/**
 * Reads models and enums from a Prisma schema. Only what the diagram and the
 * documentation checks need: block names, scalar fields and relation fields.
 *
 * @param {string} text The schema file.
 * @returns {{ models: Map<string, Array<{ name: string, type: string, list: boolean, optional: boolean, attributes: string }>>, enums: Map<string, string[]> }}
 */
export function parseSchema(text) {
  const models = new Map();
  const enums = new Map();
  // Blocks are `model Name {` … `}` and `enum Name {` … `}` with the brace on its own line.
  const block = /^(model|enum)\s+(\w+)\s*\{([\s\S]*?)^\}/gm;
  for (const [, kind, name, body] of text.matchAll(block)) {
    const lines = body
      .split('\n')
      .map((line) => line.replace(/\/\/.*$/, '').trim())
      .filter((line) => line !== '' && !line.startsWith('@@'));
    if (kind === 'enum') {
      enums.set(
        name,
        lines.map((line) => line.split(/\s+/)[0]),
      );
      continue;
    }
    models.set(
      name,
      lines.map((line) => {
        const [field, type, ...rest] = line.split(/\s+/);
        return {
          name: field,
          type: type.replace(/[?[\]]/g, ''),
          list: type.endsWith('[]'),
          optional: type.endsWith('?'),
          attributes: rest.join(' '),
        };
      }),
    );
  }
  return { models, enums };
}

/**
 * Renders the Mermaid block (fenced) for a schema.
 *
 * @param {string} text The schema file.
 * @returns {string} The fenced diagram.
 */
export function renderDiagram(text) {
  const { models, enums } = parseSchema(text);
  const out = ['```mermaid', 'erDiagram'];
  const relations = [];
  for (const [model, fields] of models) {
    // Columns that hold a foreign key: named in a relation's `fields: [...]`.
    const foreign = new Set();
    for (const field of fields) {
      const match = /fields:\s*\[([^\]]*)\]/.exec(field.attributes);
      if (match === null) continue;
      for (const column of match[1].split(',')) foreign.add(column.trim());
      // The other side decides the cardinality: a list or a single back-reference.
      const back = (models.get(field.type) ?? []).filter(
        (other) => other.type === model && relationName(other) === relationName(field),
      );
      const many = back.some((other) => other.list);
      const parentSide = field.optional ? '|o' : '||';
      const childSide = many ? 'o{' : 'o|';
      relations.push(`  ${field.type} ${parentSide}--${childSide} ${model} : "${field.name}"`);
    }
    const columns = fields.filter((field) => !models.has(field.type));
    out.push(`  ${model} {`);
    for (const field of columns) {
      const keys = [];
      if (/@id\b/.test(field.attributes)) keys.push('PK');
      if (foreign.has(field.name)) keys.push('FK');
      if (/@unique\b/.test(field.attributes)) keys.push('UK');
      if (keys.length === 0) continue;
      out.push(`    ${columnType(field, enums)} ${field.name} ${keys.join(', ')}`);
    }
    out.push('  }');
  }
  out.push(...relations, '```');
  return out.join('\n');
}

/**
 * The relation name of a relation field (`@relation("Name", ...)`), or ''.
 *
 * @param {{ attributes: string }} field The field.
 * @returns {string} The name.
 */
function relationName(field) {
  return /@relation\(\s*"([^"]+)"/.exec(field.attributes)?.[1] ?? '';
}

/**
 * A Mermaid-safe column type.
 *
 * @param {{ type: string, list: boolean, attributes: string }} field The field.
 * @param {Map<string, string[]>} enums Enum names.
 * @returns {string} The type word.
 */
function columnType(field, enums) {
  const base = enums.has(field.type)
    ? field.type
    : /@db\.Uuid\b/.test(field.attributes)
      ? 'uuid'
      : field.type.toLowerCase();
  return field.list ? `${base}_list` : base;
}

/**
 * Replaces the generated block in a document.
 *
 * @param {string} markdown The document.
 * @param {string} diagram The fenced diagram.
 * @returns {string} The updated document.
 */
export function replaceBlock(markdown, diagram) {
  const start = markdown.indexOf(START);
  const end = markdown.indexOf(END);
  if (start === -1 || end < start) throw new Error(`DATA-MODEL.md needs ${START} and ${END}`);
  return `${markdown.slice(0, start)}${START}\n\n${diagram}\n\n${markdown.slice(end)}`;
}

/**
 * Renders the up-to-date document from the files on disk.
 *
 * @returns {{ current: string, expected: string }} The committed and the generated text.
 */
export function compareDocument() {
  const current = readFileSync(documentPath, 'utf8');
  const expected = replaceBlock(current, renderDiagram(readFileSync(schemaPath, 'utf8')));
  return { current, expected };
}

// Command line: check, or rewrite with --write.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { current, expected } = compareDocument();
  if (process.argv.includes('--write')) {
    writeFileSync(documentPath, expected);
  } else if (current !== expected) {
    console.error('docs/technical/DATA-MODEL.md is stale; run npm run docs');
    process.exit(1);
  }
}
